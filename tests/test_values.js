'use strict';
const assert = require('assert');
const values = require('../apps/benspa_vitals/values');
assert.strictEqual(values.instantFuel(6.72, 80), 8.4);
assert.strictEqual(values.instantFuel(6.72, 0), null);
assert.strictEqual(values.instantFuel(6.72, 4.9), null);
assert.strictEqual(values.instantFuel(null, 80), null);
assert.strictEqual(values.instantFuel(-1, 80), null);
assert.ok(Math.abs(values.averageFuel({ statusUnitOfMeasurementConsumptionBC: 1, consumptionAverage1BC1: 71 }) - 7.1) < 1e-9);
assert.ok(Math.abs(values.averageFuel({ statusUnitOfMeasurementConsumptionBC: 'VERBRAUCH_IN_L_S_100KM', consumptionAverage1BC1: 84 }) - 8.4) < 1e-9);
assert.strictEqual(values.averageFuel({ statusUnitOfMeasurementConsumptionBC: 2, consumptionAverage1BC1: 71 }), null);
assert.strictEqual(values.averageFuel({ statusUnitOfMeasurementConsumptionBC: 1, consumptionAverage1BC1: 65535 }), null);
assert.strictEqual(values.averageFuel(null), null);
assert.strictEqual(values.warmRpm(null,7000,3500,80), null);
assert.strictEqual(values.warmRpm(NaN,7000,3500,80), null);
assert.strictEqual(values.warmRpm(10,7000,3500,80), 3500);
assert.strictEqual(values.warmRpm(30,7000,3500,80), 3500);
assert.strictEqual(values.warmRpm(55,7000,3500,80), 5300);
assert.strictEqual(values.warmRpm(80,7000,3500,80), 7000);
assert.strictEqual(values.warmRpm(100,7000,3500,80), 7000);
assert.strictEqual(values.warmRpm(20,3000,3500,80), 3000);
assert.strictEqual(values.warmRpm(30,7000,3500,30), null);
const scales={};
assert.strictEqual(values.expandScale(scales,'torque',250,150,220,25),250);
assert.strictEqual(values.expandScale(scales,'torque',250,281,280,25),300);
assert.strictEqual(values.expandScale(scales,'torque',250,80,90,25),300,'Scale does not jump down during the session');
assert.strictEqual(values.expandScale(scales,'pedal',50,43,48,10),50);
assert.strictEqual(values.expandScale(scales,'pedal',50,63,68,10),70);
assert.strictEqual(values.expandScale(scales,'boost',1.5,1.51,1.6,0.25),1.75);
assert.strictEqual(values.expandScale(scales,'unknown',50,null,100,10),50,'Stale peak must not expand the scale when data is missing');
assert.strictEqual(values.expandScale({},'x',0,1,1,1),null);
console.log('Consumption: valid readings, unknown units and stationary behavior OK');
